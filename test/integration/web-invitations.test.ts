import { afterEach, expect, test } from 'bun:test';
import { join } from 'node:path';
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { accountWebFixture } from './account-web-fixture';
import { IdentityConnection } from '../../src/hub/connect/client';
import { fixtureCleanup } from '../fixture-cleanup';
import { button, hubTab, savedSession, signIn } from './hub-web';

const cleanup = fixtureCleanup([]); afterEach(() => cleanup.close());
test('Web and CLI invitation files can be used across both entrances without changing the local default', async () => {
    const h = await accountWebFixture(cleanup.resources), { page, problems: ownerProblems } = await hubTab(h.browser);
    const password = 'a synthetic invitation passphrase';
    await page.goto(h.url + '/hub'); await button(page, '没有账号？注册').click(); await signIn(page, 'invite-owner', password, '注册');
    const selected = (await savedSession(page))!.spaceId!;
    await page.getByRole('button', { name: /^当前空间：/ }).click(); await page.getByRole('menuitem', { name: '创建空间…' }).click();
    const create = page.getByRole('dialog', { name: '创建空间' }); await create.getByLabel('空间名称').fill('Cross entrance team'); await create.getByRole('button', { name: '创建空间' }).click();
    await create.waitFor({ state: 'detached' }); const target = (await savedSession(page))!.spaceId!; expect(target).not.toBe(selected);
    // The Web shows an invitation once for copying; the guest saves it to a file for the CLI.
    await page.getByRole('link', { name: '成员', exact: true }).click(); await page.getByRole('button', { name: '邀请成员' }).first().click();
    const invite = page.getByRole('dialog', { name: '邀请成员' }); await invite.getByRole('button', { name: '生成邀请' }).click();
    const file = join(h.root, 'web-invitation.txt'); writeFileSync(file, `${await invite.locator('.secret-value').innerText()}\n`, { mode: 0o600 });
    expect(readFileSync(file, 'utf8')).toMatch(/^rw_inv_[A-Za-z0-9_-]{43}\n$/);
    await invite.getByRole('button', { name: '完成' }).click(); await invite.waitFor({ state: 'detached' });
    const ownerHome = join(h.root, 'owner-client'), owner = new IdentityConnection(ownerHome, h.url);
    await owner.password('invite-owner', password); await owner.complete({ spaceId: selected });
    const guest = new IdentityConnection(h.clientHome, h.url); await guest.password('invite-guest', password, true); await guest.complete();
    const original = guest.status().spaceId;
    const accepted = await h.cli(['space', 'invitation', 'accept', '--file', file]);
    expect(accepted.space.id).toBe(target); expect(guest.status().spaceId).toBe(original);
    const cliFile = join(h.root, 'cli-invitation.txt');
    const issued = await h.cli(['--space', selected, 'space', 'invitation', 'create', '--output', cliFile], ownerHome);
    const secret = readFileSync(cliFile, 'utf8').trim();
    expect(JSON.stringify(issued)).not.toContain(secret); expect(statSync(cliFile).mode & 0o777).toBe(0o600);
    const { page: other, problems } = await hubTab(h.browser); await other.goto(h.url + '/hub'); await signIn(other, 'invite-guest', password);
    await other.getByRole('button', { name: /^当前空间：/ }).click(); await other.getByRole('menuitem', { name: '接受邀请…' }).click();
    const dialog = other.getByRole('dialog', { name: '接受空间邀请' }); await dialog.getByLabel('邀请').fill(secret); await dialog.getByRole('button', { name: '加入空间' }).click();
    await dialog.waitFor({ state: 'detached' }); expect((await savedSession(other))!.spaceId).toBe(selected);
    expect(await other.locator('body').innerText()).not.toContain(secret); expect([...ownerProblems, ...problems]).toEqual([]);
    expect(guest.status().spaceId).toBe(original); expect(owner.status().spaceId).toBe(selected);
}, 60_000);
