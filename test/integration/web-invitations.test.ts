import { afterEach, expect, test } from 'bun:test';
import { join } from 'node:path';
import { readFileSync, statSync } from 'node:fs';
import { accountWebFixture } from './account-web-fixture';
import { IdentityConnection } from '../../src/hub/connect/client';
import { fixtureCleanup } from '../fixture-cleanup';

const cleanup = fixtureCleanup([]); afterEach(() => cleanup.close());
test('Web and CLI invitation files can be used across both entrances without changing the local default', async () => {
    const h = await accountWebFixture(cleanup.resources), page = await h.browser.newPage();
    const password = 'a synthetic invitation passphrase';
    await page.goto(h.url + '/hub'); await page.locator('#toggle-auth').click();
    await page.locator('#account-username').fill('invite-owner'); await page.locator('#account-password').fill(password); await page.locator('#auth-submit').click();
    await page.locator('#workspace').waitFor();
    const selected = await page.locator('#space-id').innerText();
    await page.getByText('创建协作空间', { exact: true }).click();
    await page.locator('#new-space-name').fill('Cross entrance team'); await page.locator('#create-space button[type=submit]').click();
    await page.locator('#spaces button').filter({ hasText: 'Cross entrance team' }).click();
    await page.waitForFunction(id => document.getElementById('space-id')?.textContent !== id, selected);
    const target = await page.locator('#space-id').innerText();
    await page.locator('#console-navigation').getByRole('button', { name: '成员', exact: true }).click();
    await page.locator('#create-invitation button[type=submit]').click(); await page.locator('#secret-dialog[open]').waitFor();
    const downloading = page.waitForEvent('download'); await page.locator('#download-secret').click(); const download = await downloading;
    const file = join(h.root, 'web-invitation.txt'); await download.saveAs(file);
    expect(readFileSync(file, 'utf8')).toMatch(/^rw_inv_[A-Za-z0-9_-]{43}\n$/);
    const guest = new IdentityConnection(h.clientHome, h.url); await guest.password('invite-guest', password, true); await guest.complete();
    const original = guest.status().spaceId;
    const accepted = await h.cli(['space', 'invitation', 'accept', '--file', file]);
    expect(accepted.space.id).toBe(target); expect(guest.status().spaceId).toBe(original);
    const ownerHome = join(h.root, 'owner-client'), owner = new IdentityConnection(ownerHome, h.url);
    await owner.password('invite-owner', password); await owner.complete({ spaceId: selected });
    const cliFile = join(h.root, 'cli-invitation.txt');
    const issued = await h.cli(['--space', selected, 'space', 'invitation', 'create', '--output', cliFile], ownerHome);
    const secret = readFileSync(cliFile, 'utf8').trim();
    expect(JSON.stringify(issued)).not.toContain(secret); expect(statSync(cliFile).mode & 0o777).toBe(0o600);
    const other = await h.browser.newPage(); await other.goto(h.url + '/hub');
    await other.locator('#account-username').fill('invite-guest'); await other.locator('#account-password').fill(password); await other.locator('#auth-submit').click(); await other.locator('#workspace').waitFor();
    await other.getByText('接受空间邀请', { exact: true }).click();
    await other.locator('#invitation-token').fill(secret); await other.locator('#accept-invitation button[type=submit]').click();
    await other.locator('#spaces button').filter({ hasText: 'invite-owner' }).waitFor();
    expect(guest.status().spaceId).toBe(original); expect(owner.status().spaceId).toBe(selected);
}, 60_000);
